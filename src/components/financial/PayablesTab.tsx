import { useState, useEffect, useRef } from 'react';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { Card } from '@/components/ui/card';
import { PayablesProvider, usePayables } from '@/contexts/PayablesContext';
import PayablesMetricCards from './payables/PayablesMetricCards';
import CredoresTable from './payables/CredoresTable';
import ContasPagarTable from './payables/ContasPagarTable';
import RecorrenciasTable from './payables/RecorrenciasTable';
import { Loader2 } from 'lucide-react';
import { gerarContasRecorrentes } from '@/lib/recorrencias-storage';
import { toast } from 'sonner';

const PayablesContent = () => {
  const { credores, contasPagar, loading, refreshAll } = usePayables();
  const [activeSubTab, setActiveSubTab] = useState('contas');

  const handleRefresh = async () => {
    await refreshAll();
  };

  // Auto-generate recurring bills on mount (runs once regardless of active tab)
  const hasAutoGenerated = useRef(false);
  useEffect(() => {
    if (hasAutoGenerated.current || loading) return;
    hasAutoGenerated.current = true;
    const autoGenerate = async () => {
      try {
        const count = await gerarContasRecorrentes();
        if (count > 0) {
          toast.success(`${count} conta(s) recorrente(s) gerada(s) automaticamente!`);
          refreshAll();
        }
      } catch (error) {
        console.error('Error auto-generating:', error);
      }
    };
    autoGenerate();
  }, [loading]);

  if (loading) {
    return (
      <div className="flex items-center justify-center py-12">
        <Loader2 className="h-8 w-8 animate-spin text-muted-foreground" />
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <PayablesMetricCards contasPagar={contasPagar} />

      <Card className="p-6">
        <Tabs value={activeSubTab} onValueChange={setActiveSubTab}>
          <TabsList className="grid w-full grid-cols-3 max-w-lg">
            <TabsTrigger value="contas">Contas a Pagar</TabsTrigger>
            <TabsTrigger value="credores">Fornecedores/Prestadores</TabsTrigger>
            <TabsTrigger value="recorrentes">Recorrentes</TabsTrigger>
          </TabsList>

          <TabsContent value="contas" className="mt-6">
            <ContasPagarTable
              contasPagar={contasPagar}
              credores={credores}
              onUpdate={handleRefresh}
            />
          </TabsContent>

          <TabsContent value="credores" className="mt-6">
            <CredoresTable
              credores={credores}
              contasPagar={contasPagar}
              onUpdate={handleRefresh}
            />
          </TabsContent>

          <TabsContent value="recorrentes" className="mt-6">
            <RecorrenciasTable
              credores={credores}
              onUpdate={handleRefresh}
              onSwitchToContas={() => setActiveSubTab('contas')}
            />
          </TabsContent>
        </Tabs>
      </Card>
    </div>
  );
};

const PayablesTab = () => {
  return (
    <PayablesProvider>
      <PayablesContent />
    </PayablesProvider>
  );
};

export default PayablesTab;
